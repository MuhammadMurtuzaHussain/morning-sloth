"""Draw the sloth's faces as ASCII art and write them out as a C header for the sketch.

The UNO Q matrix is 13 columns by 8 rows. '.' is off, '1' to '7' are grayscale
levels. Run: python3 tools/faces.py > app/sketch/faces.h
"""

FACES = {
    # Nothing needs you: eyes shut. The sketch breathes this face dim and slow.
    "asleep": [
        ".............",
        ".222.....222.",
        "22222...22222",
        "27772...27772",
        ".222.....222.",
        "......4......",
        "....3...3....",
        ".....333.....",
    ],
    # Someone wrote, it can wait until the bus: one eye open.
    "peek": [
        ".............",
        ".222.....222.",
        "22722...22222",
        "22722...27772",
        ".222.....222.",
        "......4......",
        "....3...3....",
        ".....333.....",
    ],
    # Something needs you today: both eyes wide, mouth open.
    "awake": [
        ".............",
        ".222.....222.",
        "22722...22722",
        "22722...22722",
        ".222.....222.",
        "......4......",
        ".....333.....",
        ".....3.3.....",
    ],
    # Mid-blink, used between awake frames.
    "blink": [
        ".............",
        ".222.....222.",
        "22222...22222",
        "27772...27772",
        ".222.....222.",
        "......4......",
        ".....333.....",
        ".....3.3.....",
    ],
    # Can't reach Gmail or Gemma: a single dot in the corner.
    "lost": [
        "............3",
        ".............",
        ".............",
        ".............",
        ".............",
        ".............",
        ".............",
        ".............",
    ],
}


def main():
    print("// Generated by tools/faces.py. Edit the ASCII art there, not here.")
    print("#pragma once\n#include <stdint.h>\n")
    for name, rows in FACES.items():
        assert len(rows) == 8 and all(len(r) == 13 for r in rows), name
        values = [0 if c == "." else int(c) for row in rows for c in row]
        body = ",\n  ".join(", ".join(str(v) for v in values[i:i + 13]) for i in range(0, 104, 13))
        print(f"static const uint8_t FACE_{name.upper()}[104] = {{\n  {body}\n}};\n")


if __name__ == "__main__":
    main()
